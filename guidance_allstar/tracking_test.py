def test_speed_law():
    """ModeFollow::run() sequence: P -> horizontal scale -> vertical clamp -> brake."""
    print("\n3. Rate law (sequence mode_follow.cpp)")
    complete = True

    # (a) classical arm pure P (with 'p' speed source -- mode_follow itself)
    k = TrackingController(TrackingConfig(kp=0.5, braking='disabled', speed_source='p'))
    v, kel, _ = k._speed_law(np.array([20.0, 0.0, 0.0]), 20.0, 0.05)
    complete &= _report_value("3a classic = kp*error", abs(v[0] - 10.0) < 1e-9, f"{v[0]:.2f} m/s")

    # (b) horizontal ceiling: DIRECTION IS PRESERVED
    k = TrackingController(TrackingConfig(kp=1.0, speed_ceiling_mps=35.0, braking='disabled',
                                 speed_source='p'))
    v, kel, _ = k._speed_law(np.array([60.0, 60.0, 0.0]), 84.85, 0.05)
    horizontal = math.hypot(v[0], v[1])
    complete &= _report_value("3D horizontal ceiling + direction preservation",
                    abs(horizontal - 35.0) < 1e-6 and abs(v[0] - v[1]) < 1e-9 and kel,
                    f"|v_xy|={horizontal:.2f}")

    # (c) vertical ceilings asymmetrical (WPNAV_SPEED_UP 10 / _DN 5)
    v, _, _ = k._speed_law(np.array([0.0, 0.0, -50.0]), 0.0, 0.05)
    v2, _, _ = k._speed_law(np.array([0.0, 0.0, 50.0]), 0.0, 0.05)
    complete &= _report_value("3c vertical ceiling 10 up / 5 down",
                    abs(v[2] + 10.0) < 1e-9 and abs(v2[2] - 5.0) < 1e-9,
                    f"{v[2]:.1f} / {v2[2]:.1f} m/s")

    # (d) BRAKE CLOSED vs OPEN: 25 ceiling at m = sqrt(2*2.5*(25-1.25)) = 10.90
    k_disabled = TrackingController(TrackingConfig(kp=1.0, braking='disabled', speed_source='p'))
    k_enabled = TrackingController(TrackingConfig(kp=1.0, braking='ap', speed_source='p'))
    k_enabled._last_error_z = 0.0
    error_value = np.array([25.0, 0.0, 0.0])
    v_k, _, _ = k_disabled._speed_law(error_value, 25.0, 0.05)
    v_a, _, ft = k_enabled._speed_law(error_value, 25.0, 0.05)
    expected_value = math.sqrt(2.0 * (0.5 * 5.0) * (25.0 - (0.5 * 5.0) / 2.0))
    complete &= _report_value("3d brake: 25 10.90 m/s roof (ON), 25 in closed",
                    abs(v_k[0] - 25.0) < 1e-6 and abs(v_a[0] - expected_value) < 1e-6,
                    f"closed={v_k[0]:.2f} open={v_a[0]:.2f} (ceiling {ft:.2f})")

    # (e) REASON FOR BRAKE: target speed (21 m/s) cannot be reached when open
    complete &= _report_value("21 m/s target cannot be captured if 3e brake is on (must be OFF)",
                    v_a[0] < 21.05 < v_k[0],
                    f"brake ceiling {v_a[0]:.1f} < target 21.05 < free {v_k[0]:.1f}")

    # (f) 'range' lever: far brake ON, near OFF
    k_m = TrackingController(TrackingConfig(kp=1.0, braking='range_value', braking_range_m=45.0,
                                   speed_source='p'))
    k_m._last_error_z = 0.0
    v_far, _, _ = k_m._speed_law(np.array([60.0, 0.0, 0.0]), 60.0, 0.05)
    v_near, _, _ = k_m._speed_law(np.array([25.0, 0.0, 0.0]), 25.0, 0.05)
    complete &= _report_value("3f 'range' lever (45 m threshold)",
                    v_far[0] < 20.0 and abs(v_near[0] - 25.0) < 1e-6,
                    f"60 m -> {v_far[0]:.1f}, 25 m -> {v_near[0]:.1f} m/s")

    # (g) poscon handle: SLOWER than classic outside linear region
    k_p = TrackingController(TrackingConfig(law='poscon', braking='disabled', speed_source='p'))
    v_p, _, _ = k_p._speed_law(np.array([25.0, 0.0, 0.0]), 25.0, 0.05)
    complete &= _report_value("3g poscon (Copter>=4.5) sqrt kolu",
                    5.0 < v_p[0] < 20.0 and v_p[0] < v_k[0],
                    f"poscon={v_p[0]:.2f} vs classical={v_k[0]:.2f} m/s")

    # (h) speed_source='ceiling' (DEFAULT): magnitude INDEPENDENT of range, direction does not change --
    # direction/speed separation of plane_follow.
    k_t = TrackingController(TrackingConfig(braking='disabled'))       # default ceiling
    v_far, _, _ = k_t._speed_law(np.array([60.0, 0.0, 0.0]), 60.0, 0.05)
    v_near, _, _ = k_t._speed_law(np.array([5.0, 0.0, 0.0]), 5.0, 0.05)
    v_tilted, _, _ = k_t._speed_law(np.array([10.0, 10.0, 0.0]), 14.14, 0.05)
    complete &= _report_value("3h 'ceiling': speed independent of range, direction maintained",
                    abs(v_far[0] - 35.0) < 1e-6 and abs(v_near[0] - 35.0) < 1e-6
                    and abs(v_tilted[0] - v_tilted[1]) < 1e-9,
                    f"60 m -> {v_far[0]:.1f}, 5 m -> {v_near[0]:.1f} m/s")

    # (i) acceleration shaping: trims the increment of the command SIZE
    k_s = TrackingController(TrackingConfig(braking='disabled', acceleration_shaping_mps2=2.0))
    k_s._last_v_ned = np.array([17.0, 0.0, 0.0])
    v_s, _, _ = k_s._speed_law(np.array([60.0, 0.0, 0.0]), 60.0, 0.05)
    complete &= _report_value("3i acceleration shaping ( 2 m/s ^ 2 , dt= 0.05 -> + 0.1 m/s )",
                    abs(float(np.linalg.norm(v_s)) - 17.1) < 1e-6,
                    f"|v|={float(np.linalg.norm(v_s)):.2f} m/s")
    return complete


