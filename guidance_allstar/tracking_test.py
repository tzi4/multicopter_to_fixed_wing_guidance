    print("\n6b. Range independence (not relying on ground detection)")
    complete = True

    def _command_vec(config_value, r_measure, **kw):
        k = TrackingController(config_value)
        k.seed_value2({'cmd_vel_ned': [20.0, 0.0, 0.0]})
        # Styling trims the size in the first loop; It does not affect DIRECTION.
        return np.asarray(k.command_value(_measurement(r=r_measure, **kw)).vel_ned, float)

