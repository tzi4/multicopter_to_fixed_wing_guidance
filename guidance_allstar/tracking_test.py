    complete &= _report_value("6b-a default: command range INDEPENDENT",
                    np.allclose(v1, v2, atol=1e-12)
                    and np.allclose(v1, v3, atol=1e-12),
                    f"10 m: {np.round(v1, 4).tolist()} == 200 m: "
                    f"{np.round(v3, 4).tolist()}")

    # (b) same command when there is NO range (measurement None)
    k = TrackingController(TrackingConfig())
    k.seed_value2({'cmd_vel_ned': [20.0, 0.0, 0.0]})
    o = _measurement(r=None, ex=4.0, ey=-6.0)
