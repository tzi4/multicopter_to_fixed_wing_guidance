def test_target_estimation():
    """ex/ey/range -> target NED location; Step that replaces AP_Follow."""
    print("\n2. Target estimation (vision + range -> NED)")
    complete = True
    k = TrackingController(TrackingConfig())

    # (a) nose to the north, target straight ahead and at equal altitude
    o = _measurement(ex=0.0, ey=0.0, r=50.0, yaw=0.0, pos=(0.0, 0.0, -60.0))
    target_value, u = k._target_estimate(o, 50.0, 0.0, 0.0)
    complete &= _report_value("2a right ahead", np.allclose(target_value, [50.0, 0.0, -60.0], atol=1e-6),
                    f"{np.round(target_value, 2).tolist()}")

    # (b) ex=+30 -> target is on the RIGHT (east is at yaw=0)
    target_value, u = k._target_estimate(o, 50.0, 30.0, 0.0)
    complete &= _report_value("2b ex>0 -> right",
                    target_value[1] > 24.9 and abs(target_value[0] - 43.3) < 0.1,
                    f"{np.round(target_value, 2).tolist()}")

    # (c) eps=+20 (target UP) -> NED z REDUCES (altitude increases)
    target_value, u = k._target_estimate(o, 50.0, 0.0, 20.0)
    complete &= _report_value("2c eps>0 -> target above",
                    abs(target_value[2] - (-60.0 - 50.0 * math.sin(math.radians(20)))) < 1e-6,
                    f"z={target_value[2]:.2f} (altitude {-target_value[2]:.1f} m)")

    # (d) Turning with yaw: if the nose is facing east, ex=0 puts the target EAST
    o2 = _measurement(yaw=math.radians(90.0))
    target_value, u = k._target_estimate(o2, 50.0, 0.0, 0.0)
    complete &= _report_value("2d yaw cevrimi", np.allclose(target_value, [0.0, 50.0, -60.0], atol=1e-6),
                    f"{np.round(target_value, 2).tolist()}")

    # (e) REVERSE SOLUTION: ex / eps should give the same point (pure geometry except gimbal chain) in
    # back estimation generated from random targets.
    rng = np.random.default_rng(7)
    worst_value = 0.0
    for _ in range(200):
        pos = rng.normal(0.0, 100.0, 3)
        yaw = rng.uniform(-math.pi, math.pi)
        d = rng.normal(0.0, 40.0, 3)
        r = float(np.linalg.norm(d))
        if r < 1.0:
            continue
        c, s = math.cos(yaw), math.sin(yaw)
        dh = np.array([c * d[0] + s * d[1], -s * d[0] + c * d[1], d[2]])
        ex = math.degrees(math.atan2(dh[1], dh[0]))
        eps = math.degrees(math.atan2(-dh[2], math.hypot(dh[0], dh[1])))
        o3 = _measurement(pos=tuple(pos), yaw=yaw)
        target_value, _ = k._target_estimate(o3, r, ex, eps)
        worst_value = max(worst_value, float(np.linalg.norm(target_value - (pos + d))))
    complete &= _report_value("2e inverse solution (200 random)", worst_value < 1e-9,
                    f"biggest error {worst_value:.2e} m")
    return complete


