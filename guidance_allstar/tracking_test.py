def test_sqrt_controller():
    """Are all three arms of the AP_Math/control.cpp port correct?"""
    print("\n1. sqrt_controller (AP_Math/control.cpp portu)")
    complete = True

    # (a) pure P if there is no second-order ceiling
    complete &= _report_value("1a ceiling= 0 -> pure P",
                    abs(sqrt_controller(10.0, 0.5, 0.0, 0.1) - 5.0) < 1e-9)

    # (b) p= 0 -> pure sqrt ( 2 *a*x)
    expected_value = math.sqrt(2.0 * 2.5 * 20.0)
    v = sqrt_controller(20.0, 0.0, 2.5, 0.0)
    complete &= _report_value("1b p=0 -> sqrt(2*a*x)", abs(v - expected_value) < 1e-9,
                    f"{v:.3f} m/s")

    # (c) hybrid: linear region |x| <a/p^2, outside handle sqrt
    p, a = 1.0, 2.5
    linear = a / (p * p)                      # 2.5 m
    ic = sqrt_controller(1.0, p, a, 0.0)
    dis = sqrt_controller(25.0, p, a, 0.0)
    dis_bek = math.sqrt(2.0 * a * (25.0 - linear / 2.0))
    complete &= _report_value("1c hybrid arms",
                    abs(ic - 1.0) < 1e-9 and abs(dis - dis_bek) < 1e-9,
                    f"inside={ic:.2f} outside={dis:.2f} (linear limit {linear:.1f} m)")

    # (d) sign aspect
    complete &= _report_value("1d odd function (with inverse sign)",
                    abs(sqrt_controller(-25.0, p, a, 0.0) + dis) < 1e-9)

    # (e) dt clamp: overcoming error in one step
    v = sqrt_controller(0.1, 10.0, 0.0, 0.05)   # P output 1.0, limit 0.1/0.05=2
    v2 = sqrt_controller(0.1, 100.0, 0.0, 0.05)  # P output is clipped to 10 -> 2
    complete &= _report_value("1e dt clamp", abs(v - 1.0) < 1e-9 and abs(v2 - 2.0) < 1e-9,
                    f"{v:.2f} / {v2:.2f} m/s")

    # (f) 2D form preserves orientation
    e = np.array([3.0, 4.0])
    v2d = sqrt_controller_2d(e, 1.0, 2.5, 0.0)
