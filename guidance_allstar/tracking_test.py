# ========================================================= 8. closed loop

def scenario_run(route="straight", handoff="tail", config_value=None, duration_value=25.0, seed_value=3,
                loop_hz=20.0, target_speed_mps=20.0, jitter=True,
                collision_m=2.0, miss_finish=True, target_altitude_m=60.0,
                loss_finish_s=1.5, range_disruption=None, gimbal_camera=None):
    """mpc_test.TrackingController version of scenario_run (same engine, same output).

    Engine mpc_test. Simulation: point-mass fighter, REAL virtual gimbal, LPF of the
    skeleton/clamp/acceleration chain. So the numbers here can be directly compared to the numbers
    of MPC produced with the same function."""
    # gimbal_camera=None -> engine own default (True in gimbal branch). By issuing False the OLD
    # body-fixed physics returns; essential to SEPARATE law change from physics change (see
    # ARDUPILOT_TRACKING.md 6e).
    ek = {} if gimbal_camera is None else {'gimbal_camera': bool(gimbal_camera)}
    b = Simulation(route=route, handoff=handoff, seed_value=seed_value, loop_hz=loop_hz,
                 target_altitude_m=target_altitude_m, target_speed_mps=target_speed_mps, **ek)
    k = TrackingController(config_value or TrackingConfig())
    k.seed_value2({'cmd_vel_ned': b.v.copy().tolist()})
    rng = np.random.default_rng(seed_value + 100)

    t = 0.0
    min_r = 1e9
    r0 = None
    loss_value = 0
    count_value = 0
    loss_consecutive = 0.0
    min_r_fresh = 1e9         # Closest range reached while STILL SEEING
    v_last = b.v.copy()
    last_request = None
    # SEPARATE RNG TO DISTORTOR: main rng produces loop jitter (dt); If the jammer pulls from it, the
    # jitter array shifts and the ORBIT changes -- so what reads as "noise disturbed range" is actually a
    # different dt array. This trap was fallen once (the noise lever showed 1.60 instead of 1.35 ); makes
    # separate seed arms EXACTLY comparable.
    disturbance_rng = np.random.default_rng(seed_value + 900)
    cmd_speeds = []
    closures = []
    miss_t = None
    miss_reason = ''
    finish = 'duration_elapsed'
    while t < duration_value:
        dt = b.dt_nom
        if jitter:
            dt = b.dt_nom * (1.0 + 0.25 * rng.random())
            if rng.random() < 0.04:
                dt = b.dt_nom * (2.0 + 1.0 * rng.random())
        o, visible, r = b.measurement(dt)
        if range_disruption is not None:
            # RANGE DISTURBANCE: only contaminates the MEASUREMENT; The ACTUAL r returned by b.metric (for
            # metrics) remains untouched. This is the right place to emulate ground detection error -- common
            # engine
            # (mpc_test.Simulation) hic dokunulmuyor.
            o.range_m_value = range_disruption(o.range_m_value, t, disturbance_rng)
        if r0 is None:
            r0 = r
        min_r = min(min_r, r)
        count_value += 1
        if visible:
            loss_consecutive = 0.0
            min_r_fresh = min(min_r_fresh, r)
            c = k.command_value(o)
            request_value = np.asarray(c.vel_ned, dtype=float)
            yaw_cmd = c.yaw_rate_dps
            last_request = request_value.copy()
            cmd_speeds.append(float(np.linalg.norm(request_value)))
            if getattr(c, 'release_value', False) and miss_t is None:
                miss_t, miss_reason = t, c.release_reason
                if miss_finish:
                    finish = 'miss_value'
                    break
        else:
            loss_value += 1
            loss_consecutive += dt
            # missing behavior of SKELETON (visual_base.run): age <= 0.7 s -> controller is already called
            # (above) 0.7 < age <= 1.7 s -> LAST command is KEPT (except yaw) age > 1.7 s -> GLIding: command =
            # MEASURED speed (acceleration 0)
            if loss_consecutive <= 1.0 and last_request is not None:
                request_value = last_request
            else:
                request_value = b.v.copy()
            yaw_cmd = None
        # closing speed (ANALYSIS): relative speed along LOS
        d = b.q - b.p
        n = float(np.linalg.norm(d))
        if n > 1e-6:
            closures.append(float((b.v - np.array(
                [b.target_speed * math.cos(b.target_direction),
                 b.target_speed * math.sin(b.target_direction), 0.0])) @ (d / n)))
        b.advance(request_value, yaw_cmd, dt)
        t += dt
        v_last = b.v.copy()
        if collision_m > 0.0 and r <= collision_m:
            finish = 'collision'
            break
        if b.altitude_value < 5.0:
            finish = 'ground_contact'
            break
        if loss_consecutive > loss_finish_s:
            # SAME rule as mpc_test (LOSS_FINISH_S): when it is left out of frame for this long, the decision
            # maker gives the authority back to the positioner, that is, THE VISUAL SEGMENT ENDS. Continuing the
            # run would be blindly measuring glide as "steering quality".
            finish = 'framing_loss'
            break
    return {
        'route': route, 'handoff': handoff, 'seed_value': seed_value, 'duration_value': t,
        'r0': r0, 'min_r': min_r, 'min_r_fresh': min_r_fresh, 'finish': finish,
        'loss_pct': 100.0 * loss_value / max(count_value, 1),
        'cmd_p95': float(np.percentile(cmd_speeds, 95)) if cmd_speeds else 0.0,
        'cmd_max': float(np.max(cmd_speeds)) if cmd_speeds else 0.0,
        'closure_mean': float(np.mean(closures)) if closures else 0.0,
        'miss_t': miss_t, 'miss_reason': miss_reason,
        'min_altitude': b.min_altitude, 'state_value': k.state_value, 'hit_value': k.hit_value,
        'speed_last': float(np.linalg.norm(v_last)),
    }


