    repeat = k._impact_successful_control(_measurement(r=1.0, vibe=25.0), 1.0)
    complete &= _report_value("6e contact detection (vibe + range, latch)",
                    absent is None and absent2 is None and var is not None
                    and repeat is None and k.hit_value,
                    var[1] if var else '')
    return complete


