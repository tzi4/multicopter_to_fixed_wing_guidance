    o1 = _command_vec(O, 20.0, ex=4.0, ey=-6.0)
    o2 = _command_vec(O, 60.0, ex=4.0, ey=-6.0)
    complete &= _report_value("6b-d offset ON -> connects to range (so 0)",
                    not np.allclose(o1, o2, atol=1e-6),
                    "There is no cost as the offset in the multiplication setting is 0")

    # (e) WHERE RANGE ENTERS: lone state machine. If we run the same measurement flow with two different
    # ranges, the commands should be the same but the situations should be different.
    def _states(r_multiplier):
        k = TrackingController(TrackingConfig())
        k.seed_value2({'cmd_vel_ned': [20.0, 0.0, 0.0]})
        states_value, commands = [], []
        for i in range(60):
            r_actual = 60.0 - i * 0.8
            c = k.command_value(_measurement(r=r_actual * r_multiplier, t=i * 0.05,
                               ex=2.0, ey=-4.0))
            states_value.append(k.state_value)
            commands.append(np.asarray(c.vel_ned, float).copy())
        return states_value, np.array(commands)

    d1, c1 = _states(1.0)
    d2, c2 = _states(0.5)       # range is reported as HALF
    complete &= _report_value("6b-e when the range is broken, the COMMAND is the same, the SITUATION changes",
                    np.allclose(c1, c2, atol=1e-12) and d1 != d2,
                    f"phase switch {d1.count('IMPACT')} -> {d2.count('IMPACT')} loop")
    return complete


